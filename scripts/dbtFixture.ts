// The dbt project the semantic parity matrix asks on a real dbt Cloud account (semantic layer part 7, d1, BETA;
// docs/live-data/dbt-semantic-layer.md). Helper, not a suite.
//
// scripts/fixtures/dbt-sl/project/ holds two files GENERATED here, for the owner to add to the dbt Cloud project the
// nightly's environment deploys (on the nightly's Snowflake account): a model selecting the live-parity fixture's rows
// from literals (c1's Snowflake literal twin), and its semantic model, metrics and the saved query `ordinate_parity`.
// test-semanticDbt checks the checked-in files still equal what this writes.
//
//   node -e "require('./scripts/dbtFixture.js').writeFixture()"
//
// Dimensions are the fixture's columns, qualified by the primary entity (`order__many`, …, dbt's group-by names);
// metrics are scripts/semanticFake.ts's, so the matrix asks dbt exactly what it asks the fake. Every categorical
// dimension is NULLIF(…, ''): dbt groups '' and NULL apart where Ordinate keeps one blank (to verify: the entity's
// key, `bigid`, is not unique; MetricFlow needs no uniqueness to group within one semantic model).

const fx: typeof import('./liveParityFixture') = require('./liveParityFixture');
const literal: typeof import('./liveParityLiteral') = require('./liveParityLiteral');

export const SAVED_QUERY = 'ordinate_parity';
/** The primary entity's prefix on every group-by name. */
export const PREFIX = 'order__';
export const MODEL = 'ordinate_parity_rows';
export const MEASURES: ReadonlyArray<{ name: string; agg: 'sum' | 'count' | 'average' | 'max'; expr: string }> = [
  { name: 'revenue', agg: 'sum', expr: '"amt"' },
  { name: 'orders', agg: 'count', expr: '1' },
  { name: 'avg_amount', agg: 'average', expr: '"amt"' },
  { name: 'max_amount', agg: 'max', expr: '"amt"' },
];

const q = (s: string): string => JSON.stringify(s); // a JSON string is a YAML scalar

export function modelSql(): string {
  const layout = fx.layout(fx.COLUMNS).map((c) => (c.name === 'bigid' ? { ...c, store: 'text' as const } : c));
  return [
    '-- The live-parity fixture as a table (docs/live-data/dbt-semantic-layer.md, the nightly).',
    '-- GENERATED by scripts/dbtFixture.ts from the live-parity fixture: do not edit by hand.',
    "{{ config(materialized='table') }}",
    '',
    literal.literalTwin(literal.SNOWFLAKE, 'snowflake', layout, fx.fixtureRows()),
    '',
  ].join('\n');
}

export function semanticYaml(): string {
  const dims = fx.COLUMNS.map((c) => (c.type === 'date'
    ? [`      - name: ${c.name}`, '        type: time', `        expr: ${q(`"${c.name}"`)}`, '        type_params:', '          time_granularity: day']
    : [`      - name: ${c.name}`, '        type: categorical', `        expr: ${q(`NULLIF(CAST("${c.name}" AS VARCHAR), '')`)}`]).join('\n'));
  return [
    '# The semantic model, metrics and saved query the dbt parity nightly asks (docs/live-data/dbt-semantic-layer.md).',
    '# GENERATED by scripts/dbtFixture.ts: do not edit by hand.',
    '',
    'semantic_models:',
    '  - name: ordinate_parity_orders',
    '    description: Every order of the live-parity fixture',
    `    model: ref('${MODEL}')`,
    '    defaults:',
    '      agg_time_dimension: d',
    '    entities:',
    '      - name: order',
    '        type: primary',
    `        expr: ${q('"bigid"')}`,
    '    dimensions:',
    ...dims,
    '    measures:',
    ...MEASURES.map((m) => [`      - name: ${m.name}_measure`, `        agg: ${m.agg}`, `        expr: ${q(m.expr)}`].join('\n')),
    '',
    'metrics:',
    ...MEASURES.map((m) => [`  - name: ${m.name}`, `    label: ${m.name}`, '    type: simple', '    type_params:', `      measure: ${m.name}_measure`].join('\n')),
    '',
    'saved_queries:',
    `  - name: ${SAVED_QUERY}`,
    '    label: Ordinate parity',
    '    query_params:',
    '      metrics:',
    ...MEASURES.map((m) => `        - ${m.name}`),
    '      group_by:',
    ...fx.COLUMNS.map((c) => `        - ${q(c.type === 'date' ? `TimeDimension('${PREFIX}${c.name}', 'day')` : `Dimension('${PREFIX}${c.name}')`)}`),
    '',
  ].join('\n');
}

/** The generated files, by their path under scripts/fixtures/dbt-sl/project. */
export function fixtureFiles(): Record<string, string> {
  return { [`models/${MODEL}.sql`]: modelSql(), 'models/ordinate_parity.yml': semanticYaml() };
}

export function writeFixture(): void {
  const fs: typeof import('fs') = require('fs');
  const path: typeof import('path') = require('path');
  for (const [file, text] of Object.entries(fixtureFiles())) {
    const at = path.join(__dirname, 'fixtures', 'dbt-sl', 'project', file);
    fs.mkdirSync(path.dirname(at), { recursive: true });
    fs.writeFileSync(at, text);
  }
}
